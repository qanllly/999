import random

# --- ФУНКЦИИ ПРОВЕРКИ И ВЫВОДА ---

def get_input(pr):
    infinity_check = True
    while (infinity_check):
        s = input(pr)
        if not s:
            print("Ошибка: ввод не может быть пустым")
            continue
        is_num = False
        if s[0] == '-' and len(s) > 1 and s[1:].isdigit():
            is_num = True
        elif s.isdigit():
            is_num = True
            
        if is_num:
            return int(s)
        print("Ошибка: введите корректное целое число")

def print_results_table(results):
    header = f"| {'Метод сортировки':<20} | {'Сравнения':<12} | {'Перестановки':<14} |"
    line = "-" * len(header)
    print(line)
    print(header)
    print(line)
    for name, comp, swap in results:
        print(f"| {name:<20} | {comp:<12} | {swap:<14} |")
    print(line)

# --- АЛГОРИТМЫ СОРТИРОВОК ---

def selection_sort(lst):
    arr = list(lst)
    comparisons = 0
    swaps = 0
    n = len(arr)
    for i in range(n - 1):
        min_idx = i
        for j in range(i + 1, n):
            comparisons += 1
            if arr[j] < arr[min_idx]:
                min_idx = j
        if min_idx != i:
            arr[i], arr[min_idx] = arr[min_idx], arr[i]
            swaps += 1
    return arr, comparisons, swaps

def bubble_sort(lst):
    arr = list(lst)
    comparisons = 0
    swaps = 0
    n = len(arr)
    for i in range(n - 1):
        is_sorted = True
        for j in range(n - 1 - i):
            comparisons += 1
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                swaps += 1
                is_sorted = False
        if is_sorted:
            break
    return arr, comparisons, swaps

def quick_sort(arr):
    if len(arr) <= 1:
        return arr, 0, 0
    
    pivot = arr[random.randint(0, len(arr) - 1)]
    comparisons = len(arr)
    
    less = [x for x in arr if x < pivot]
    equal = [x for x in arr if x == pivot]
    greater = [x for x in arr if x > pivot]
    
    sorted_less, c1, s1 = quick_sort(less)
    sorted_greater, c2, s2 = quick_sort(greater)
    
    return sorted_less + equal + sorted_greater, comparisons + c1 + c2, s1 + s2

